#!/usr/bin/env python3
"""Display the original schematic PNGs on a white SVG canvas without changing them."""

import base64
from html import escape
from pathlib import Path
import struct


IMAGES = [
    ("ALU", "alu", "16-bit arithmetic and logic unit"),
    ("RegisterFile", "register-file", "Register file with two operand reads and a debug read"),
    ("ControlUnit", "control-unit", "ROM-based instruction control unit"),
    ("FlagRegister", "flag-register", "Four-bit status flag register"),
    ("ConditionEvaluator", "condition-evaluator", "Instruction condition evaluator"),
    ("SignExtend", "sign-extend", "Immediate and branch-offset sign extension"),
    ("DataMemory", "data-memory", "Data memory with an independent debug read port"),
]


def main():
    images = Path(__file__).resolve().parents[1] / "docs/images"
    output = images / "gallery"
    output.mkdir(exist_ok=True)
    for source, name, title in IMAGES:
        png = (images / f"{source}.png").read_bytes()
        if png[:8] != b"\x89PNG\r\n\x1a\n" or png[12:16] != b"IHDR":
            raise ValueError(f"{source}.png is not a PNG with an IHDR header")
        width, height = struct.unpack(">II", png[16:24])
        encoded = base64.b64encode(png).decode("ascii")
        svg = (
            '<?xml version="1.0" encoding="UTF-8"?>\n'
            '<!-- Generated by scripts/prepare_image_gallery.py; embedded PNG is unchanged. -->\n'
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
            f'viewBox="0 0 {width} {height}" role="img" aria-labelledby="title">\n'
            f'  <title id="title">{escape(title)}</title>\n'
            f'  <rect width="{width}" height="{height}" fill="white"/>\n'
            f'  <image width="{width}" height="{height}" href="data:image/png;base64,{encoded}"/>\n'
            '</svg>\n'
        )
        (output / f"{name}.svg").write_text(svg, encoding="utf-8")
    print(f"Prepared {len(IMAGES)} schematic previews; original PNG files are unchanged.")


if __name__ == "__main__":
    main()
